<h3>Calculation of Net WPM </h3>
<p>Net speed can be calculated by deducting errors in gross word per minute. For example if you typed 50 Word in 1 Minute but you typed 4 word wrong then your Net WPM = 50 - 4 = 46 WPM </p>


<h3>Accuracy Formula: </h3>
<p>Accuracy is a percentage ratio of Gross and Net Word Speed:
Accuracy = (Net WPM / Gross WPM ) * 100 = 46 / 50 * 100 = 92 % </p>

